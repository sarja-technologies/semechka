#!/usr/bin/env python3
"""Generate reference docs from the code so they cannot drift: docs/CONFIGURATION.md and docs/PERMISSIONS.md."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "backend"))
from semechka import perms, settings_reg as R  # noqa: E402

root = pathlib.Path(__file__).resolve().parents[1] / "docs"
root.mkdir(exist_ok=True)

lines = ["# Configuration reference", "", "Generated by `scripts/gen_docs.py` from `backend/semechka/settings_reg.py`. Every setting below has a control in "
         "Admin → Settings (searchable), the same validation over the API (`PUT /api/admin/settings/{id}`), audit and rollback.", "",
         "Merge rules when a value is set at several scopes: **specific** = the most specific scope wins (user > team > role > deployment); "
         "**false_wins** = any *off* wins, and a deployment-level off is a ceiling; **min** = lowest limit; **min_nonzero** = lowest non-zero (0 = unlimited); "
         "**min_nonneg** = shortest retention (-1 = forever).", ""]
cat = None
for d in R.DEFS:
    if d.category != cat:
        cat = d.category
        lines += [f"## {cat}", "", "| ID | Type | Default | Scopes | Merge | Edit permission | Notes |", "|---|---|---|---|---|---|---|"]
    default = "(write-only)" if d.secret else ("*(computed)*" if d.default is None else f"`{d.default}`".replace("|", "\\|"))
    notes = []
    if d.requires:
        notes.append(f"needs capability `{d.requires}`")
    if d.lowers_privacy:
        notes.append("weakening changes need confirmation")
    if d.apply == "restart":
        notes.append("applies on restart")
    if d.effect:
        notes.append(d.effect)
    lines.append(f"| `{d.id}` | {d.type} | {default[:60]} | {', '.join(d.scopes)} | {d.merge} | `{d.edit_perm}` | {' · '.join(notes)} |")
    if d is R.DEFS[-1] or R.DEFS[R.DEFS.index(d) + 1].category != cat:
        lines.append("")
(root / "CONFIGURATION.md").write_text("\n".join(lines) + "\n")

L = ["# Permission matrix", "", "Generated from `backend/semechka/perms.py`. Evaluation: a permission is allowed iff some role/team/user rule grants it and **no** rule denies it. "
     "`*` grants every permission except those marked sensitive. Reading technical information (`tech.*`), operating infrastructure (`ops.*`) and administering (`admin.*`) are separate families.", ""]
roles = perms.ROLE_TEMPLATES
L += ["## Role templates (starting points; every role is editable and renamable, ids are stable)", "",
      "| Permission | " + " | ".join(r["label"] for r in roles) + " |", "|---|" + "---|" * len(roles)]
class _P(perms.Principal):
    pass
principals = []
for r in roles:
    src = perms.Source("role", r["id"], r["label"], r["grants"], r["denies"])
    principals.append(perms.Principal("x", "active", [src], [r["id"]], []))
grp = None
for p in perms.REGISTRY:
    if p.group != grp:
        grp = p.group
        L.append(f"| **{grp}** |" + " |" * len(roles))
    L.append(f"| `{p.id}` — {p.label} | " + " | ".join("yes" if pr.can(p.id) else "–" for pr in principals) + " |")
L += ["", "## Technical-visibility presets (editable shortcuts)", ""]
for k, v in perms.TECH_PRESET_DEFAULTS.items():
    L.append(f"- **{k}**: " + (", ".join(f"`{x}`" for x in v) if v else "no technical fields"))
(root / "PERMISSIONS.md").write_text("\n".join(L) + "\n")
print("wrote docs/CONFIGURATION.md and docs/PERMISSIONS.md")
